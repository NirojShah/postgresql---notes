-- WE CAN DO THE SUBTRATION AND ADDITION ON DATES.

-- SUBTRACTION

SELECT NOW();

-- INTERVAL - we will use this keyword.

SELECT NOW() - INTERVAL '1 YEAR'; -- 2025-07-25 18:53:03.20181+00


SELECT NOW() - INTERVAL '1 MONTH'; -- 2026-06-25 18:53:48.933075+00


SELECT NOW() - INTERVAL '10 DAYS'; -- 2026-07-15 18:53:35.188434+00


-- IF YOU WANT DATE ONLY NOT THE TIMESTAMP THEN YOU HAVE TO WRAP 
-- BECAUSE THE INTERVAL WILL RETURN WITH TIMESTAMP.

SELECT (NOW() - INTERVAL '10 DAYS')::DATE -- 2026-07-15


-- ADDITION


SELECT NOW() + INTERVAL '1 YEAR'; -- 2027-07-25 18:53:03.20181+00


SELECT NOW() + INTERVAL '1 MONTH'; -- 2026-08-25 18:53:48.933075+00


SELECT NOW() + INTERVAL '10 DAYS'; -- 2026-08-04 18:53:35.188434+00


-- IF YOU WANT DATE ONLY NOT THE TIMESTAMP THEN YOU HAVE TO WRAP 
-- BECAUSE THE INTERVAL WILL RETURN WITH TIMESTAMP.

SELECT (NOW() + INTERVAL '10 DAYS')::DATE -- 2026-08-04

